// Writes the public runtime config for the deployed site.
//
// Called by .github/workflows/deploy-pages.yml. Fails loudly when the
// repository variables are missing, so a deploy never publishes a page that
// silently shows no data. Never prints the key.
import fs from 'node:fs';
import path from 'node:path';

const url = String(process.env.SUPABASE_URL || '').replace(/\/+$/, '');
const key = String(process.env.SUPABASE_ANON_KEY || '');
const siteBase = String(process.env.SITE_BASE || '').replace(/\/+$/, '');

const problems = [];
if (!/^https:\/\/[a-z0-9-]+\.supabase\.co$/.test(url)) {
  problems.push('SUPABASE_URL must be https://<ref>.supabase.co');
}
if (key.length < 40) problems.push('SUPABASE_ANON_KEY is missing or too short');
if (!/^https:\/\/[a-z0-9-]+\.github\.io\/[A-Za-z0-9._-]+$/.test(siteBase)) {
  problems.push('SITE_BASE must be https://<owner>.github.io/<repo>');
}
if (problems.length) {
  for (const problem of problems) console.error(`config: ${problem}`);
  process.exit(1);
}

const body = `// Generated by site/scripts/write-config.mjs — do not edit or commit.
window.RAILMATE_CONFIG = {
  SUPABASE_URL: ${JSON.stringify(url)},
  SUPABASE_ANON_KEY: ${JSON.stringify(key)},
  SITE_BASE: ${JSON.stringify(siteBase)},
};
`;

const target = path.join(process.cwd(), 'assets', 'config.js');
fs.writeFileSync(target, body);
console.log(`config: wrote ${path.relative(process.cwd(), target)} (${url})`);
